namespace ScarletMeter.App.Pets;

/// <summary>
/// A pet's genus (the game's Pet Genus Insight), which the window colours it by; Special pets come at level 3, and a pet the
/// catalog does not know has none.
/// </summary>
public enum PetGenus
{
    Cogni,
    Fera,
    Natura,
    Varian,
    Special,
    Unknown,
}

/// <summary>How a pet is raised, which says whether the window counts it among the pets still to raise.</summary>
public enum PetKind
{
    /// <summary>Monsters on the open maps drop its souls (and Pet Soul Chests hold them).</summary>
    Farmed,
    /// <summary>No monster on the open maps drops its souls: only Pet Soul Chests (the battle pass's) raise it.</summary>
    ChestOnly,
    /// <summary>It comes at its highest level, so it has no souls to gather.</summary>
    Special,
    /// <summary>In the game's tables but not yet in the game.</summary>
    Unreleased,
}

/// <summary>A pet the catalog knows: the game's id, its English name, its genus and how it is raised.</summary>
public sealed record PetInfo(int Id, string Name, PetGenus Genus, PetKind Kind);

