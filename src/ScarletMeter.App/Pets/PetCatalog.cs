    private static readonly Dictionary<int, PetInfo> ById = All.ToDictionary(pet => pet.Id);

    /// <summary>The pet with this id, or null when the catalog does not know it.</summary>
    public static PetInfo? Find(int id) => ById.GetValueOrDefault(id);

    /// <summary>A pet's English name, or "Pet" and its id for one the catalog does not know.</summary>
    public static string NameOf(int id) => Find(id)?.Name ?? $"Pet {id}";

    /// <summary>
    /// What the catalog knows of a pet, or a farmed pet of no genus named by its id for one it does not know (newer than the
    /// catalog: the game has it, so it is counted as one to raise).
    /// </summary>
    public static PetInfo Describe(int id) => Find(id) ?? new PetInfo(id, NameOf(id), PetGenus.Unknown, PetKind.Farmed);
